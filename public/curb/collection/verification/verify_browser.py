checks=[]; errors=[]; console=[]; requests=[]; failures=[]; http_errors=[]
def check(name, condition, detail=None):
    checks.append({'name':name,'pass':bool(condition),'detail':detail})
    print(('PASS ' if condition else 'FAIL ')+name,flush=True)
    if not condition: raise AssertionError(name+': '+str(detail))
def time_at(page): return float(page.locator('[data-seconds]').get_attribute('data-seconds'))
def scrub(page, value):
    page.get_by_role('slider',name='Simulation progress').fill(str(value))
    page.wait_for_timeout(180)
def overflow(page): return page.evaluate('document.documentElement.scrollWidth <= innerWidth')
def pause_if_running(page):
    button=page.get_by_role('button',name='Pause simulation',exact=True)
    if button.count(): button.click()
def visible_anchors(page):
    return page.locator('[data-label]').evaluate_all('''els=>els.filter(e=>getComputedStyle(e).visibility==='visible').map(e=>({id:e.dataset.label,rect:e.getBoundingClientRect().toJSON()}))''')
def track(page):
    return page.locator('[data-leader]').evaluate_all('''els=>els.filter(e=>getComputedStyle(e).visibility==='visible').map(e=>({id:e.dataset.leader,d:e.getAttribute('d'),cx:e.parentNode.querySelector('circle').getAttribute('cx'),cy:e.parentNode.querySelector('circle').getAttribute('cy')}))''')
def stage_capture(page,name):
    page.locator('[data-seconds]').screenshot(path=str(OUT/name))

